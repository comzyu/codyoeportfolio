/**
 * Packs the tested prototypes (../prototypes-v2) into the app.
 * - text files (pages, scripts, styles) become strings in src/web/pack.generated.ts
 * - photos and fonts are copied to assets/web/ and required, so the bundler ships them
 * The app writes all of it into its own folder on first launch (src/web/install.ts) and opens the pages from there.
 * Run after changing any prototype: `node scripts/pack-web.js`
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const APP = path.join(__dirname, '..');
const SRC = path.join(APP, '..', 'prototypes-v2');
const EXTRA = path.join(APP, 'web-app');
const ASSETS = path.join(APP, 'assets', 'web');
const OUT = path.join(APP, 'src', 'web', 'pack.generated.ts');

const PAGES = ['home-min', 'home', 'camera', 'rolls', 'profile', 'stamp', 'postcard'];
const FONTS = [
  ['inter', 'Inter', '400Regular'], ['inter', 'Inter', '500Medium'], ['inter', 'Inter', '600SemiBold'],
  ['ibm-plex-mono', 'IBMPlexMono', '400Regular'], ['ibm-plex-mono', 'IBMPlexMono', '500Medium'], ['ibm-plex-mono', 'IBMPlexMono', '600SemiBold'], ['ibm-plex-mono', 'IBMPlexMono', '700Bold'],
  ['special-elite', 'SpecialElite', '400Regular'], ['la-belle-aurore', 'LaBelleAurore', '400Regular'],
];

const text = {};
const files = {};

for (const p of PAGES) {
  let h = fs.readFileSync(path.join(SRC, p + '.html'), 'utf8');
  h = h.replace(/<link rel="stylesheet" href="https:\/\/fonts\.googleapis\.com[^>]*>/g, '<link rel="stylesheet" href="fonts.css">');
  h = h.replace(/https:\/\/cdnjs\.cloudflare\.com\/ajax\/libs\/three\.js\/[\d.]+\/three\.min\.js/g, 'lib/three.min.js');
  h = h.replace(/<head>/, '<head>\n<script src="app.js"></script>');
  h = h.replace(/<\/head>/, '<link rel="stylesheet" href="app.css">\n</head>');
  if (/googleapis|cdnjs/.test(h)) throw new Error(p + '.html still loads something from the internet');
  text[p + '.html'] = h;
}
for (const f of fs.readdirSync(path.join(SRC, 'lib'))) text['lib/' + f] = fs.readFileSync(path.join(SRC, 'lib', f), 'utf8');
text['lib/three.min.js'] = fs.readFileSync(path.join(EXTRA, 'vendor', 'three.min.js'), 'utf8');
for (const f of ['app.js', 'app.css']) text[f] = fs.readFileSync(path.join(EXTRA, f), 'utf8');

// fonts: the same faces the pages asked Google for, from the app instead
fs.mkdirSync(path.join(ASSETS, 'fonts'), { recursive: true });
let css = '';
for (const [pkg, fam, w] of FONTS) {
  const name = fam + '_' + w + '.ttf';
  fs.copyFileSync(path.join(APP, 'node_modules', '@expo-google-fonts', pkg, w, name), path.join(ASSETS, 'fonts', name));
  files['fonts/' + name] = 'fonts/' + name;
  const family = { Inter: 'Inter', IBMPlexMono: 'IBM Plex Mono', SpecialElite: 'Special Elite', LaBelleAurore: 'La Belle Aurore' }[fam];
  css += '@font-face { font-family: "' + family + '"; font-weight: ' + parseInt(w, 10) + '; font-style: normal; font-display: block; src: url("fonts/' + name + '") format("truetype"); }\n';
}
text['fonts.css'] = css;

// photos the pages use (stock stand-ins, see img/CREDITS.md)
fs.mkdirSync(path.join(ASSETS, 'img'), { recursive: true });
for (const f of fs.readdirSync(path.join(SRC, 'img'))) {
  if (!/\.(jpg|png)$/.test(f)) continue;
  fs.copyFileSync(path.join(SRC, 'img', f), path.join(ASSETS, 'img', f));
  files['img/' + f] = 'img/' + f;
}
fs.copyFileSync(path.join(SRC, 'img', 'CREDITS.md'), path.join(ASSETS, 'img', 'CREDITS.md'));

const hash = crypto.createHash('sha1');
for (const k of Object.keys(text).sort()) hash.update(k).update(text[k]);
for (const k of Object.keys(files).sort()) hash.update(k).update(fs.readFileSync(path.join(ASSETS, files[k])));
const version = hash.digest('hex').slice(0, 12);

let out = '// Generated by scripts/pack-web.js from ../prototypes-v2. Do not edit; edit the prototypes and run the script.\n';
out += 'export const VERSION = ' + JSON.stringify(version) + ';\n';
out += 'export const TEXT: Record<string, string> = {\n' + Object.keys(text).sort().map((k) => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(text[k]) + ',').join('\n') + '\n};\n';
out += 'export const FILES: Record<string, number> = {\n' + Object.keys(files).sort().map((k) => '  ' + JSON.stringify(k) + ': require(' + JSON.stringify('../../assets/web/' + files[k]) + '),').join('\n') + '\n};\n';
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log('packed', Object.keys(text).length, 'text files,', Object.keys(files).length, 'photos and fonts; version', version);

// `--out <dir>`: also write the folder exactly as the app installs it (for checking the pages in a browser)
const at = process.argv.indexOf('--out');
if (at > 0) {
  const dir = process.argv[at + 1];
  for (const [k, v] of Object.entries(text)) { fs.mkdirSync(path.dirname(path.join(dir, k)), { recursive: true }); fs.writeFileSync(path.join(dir, k), v); }
  for (const [k, v] of Object.entries(files)) { fs.mkdirSync(path.dirname(path.join(dir, k)), { recursive: true }); fs.copyFileSync(path.join(ASSETS, v), path.join(dir, k)); }
  fs.mkdirSync(path.join(dir, 'shots'), { recursive: true });
  console.log('wrote', dir);
}
