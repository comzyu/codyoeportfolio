#!/usr/bin/env python3
"""Build theme files from tokens.json.

    python3 assets-src/theme/build_theme.py

Writes:
  assets/theme/theme.ts            for the app (typed, light + dark)
  prototypes/shared/tokens.css     for the web prototypes and the review page
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
tokens = json.loads((Path(__file__).parent / "tokens.json").read_text())


def clean(d):
    """Drop the _note keys."""
    if isinstance(d, dict):
        return {k: clean(v) for k, v in d.items() if not k.startswith("_")}
    return d


t = clean(tokens)


def ts(obj, indent=2, level=1):
    pad = " " * (indent * level)
    if isinstance(obj, dict):
        rows = [f"{pad}{k}: {ts(v, indent, level + 1)}," for k, v in obj.items()]
        return "{\n" + "\n".join(rows) + "\n" + " " * (indent * (level - 1)) + "}"
    return json.dumps(obj)


theme_ts = f"""// GENERATED by assets-src/theme/build_theme.py from tokens.json. Do not edit by hand.

export const palette = {ts({"light": {**t["color"]["light"], **t["color"]["fixed"]}, "dark": {**t["color"]["dark"], **t["color"]["fixed"]}})} as const;

export const space = {ts(t["space"])} as const;

export const radius = {ts(t["radius"])} as const;

export const type = {ts(t["type"])} as const;

export const hairline = {t["hairline"]};

export type ColorName = keyof typeof palette.light;
export type Scheme = keyof typeof palette;

export const theme = (scheme: Scheme) => ({{ color: palette[scheme], space, radius, type, hairline }});
"""
out = ROOT / "assets/theme/theme.ts"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(theme_ts)


def kebab(s):
    return re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", s).lower()


def css_vars(d, prefix=""):
    return "".join(f"  --{prefix}{kebab(k)}: {v};\n" for k, v in d.items())


light = css_vars(t["color"]["light"])
dark = css_vars(t["color"]["dark"])
fixed = css_vars(t["color"]["fixed"])
space = "".join(f"  --{k}: {v}px;\n" for k, v in t["space"].items())
radius = "".join(f"  --r-{k}: {v}px;\n" for k, v in t["radius"].items())
sizes = "".join(f"  --t-{kebab(k)}: {v}px;\n" for k, v in t["type"]["size"].items())
css = f"""/* GENERATED by assets-src/theme/build_theme.py from tokens.json. Do not edit by hand. */
:root {{
{light}{fixed}{space}{radius}{sizes}}}
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
{dark}  }}
}}
:root[data-theme="dark"] {{
{dark}}}
"""
out = ROOT / "prototypes/shared/tokens.css"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(css)
print("wrote assets/theme/theme.ts and prototypes/shared/tokens.css")
